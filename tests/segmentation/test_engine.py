class EngineTests(unittest.TestCase):
    """候选边界、回退问题与原文覆盖测试；失败需修实现而非静默改预期。"""

    def test_cases(self):
        """逐个执行冻结的61个合成边界案例，并验证结果确定性。"""
        for number, (text, expected) in enumerate(CASES, 1):
            with self.subTest(number=number, text=text):
                actual = segment(text)
                self.assertEqual([s["raw_text"] for s in actual["text_segments"]], expected)
                self.assertEqual(actual, segment(text))

    def test_malformed_flag(self):
        """原文不配对必须有提示，列表的右括号不能误报警。"""
        self.assertIn("UNBALANCED_DELIMITER", {p["code"] for p in segment("甲（乙。")['issues']})
        self.assertNotIn("UNBALANCED_DELIMITER", {p["code"] for p in segment("1)甲\n2)乙")['issues']})

    def test_fuzz_conservation(self):
        """200个固定种子的随机组合验证覆盖性，不能以是否有语义作为丢字依据。"""
        rng = random.Random(20260908)
        atoms = ["甲", "乙", "。", "!?", "\n", "\r\n", " ", "#甲#", "（", "）", "“", "”", "&#34;", "🌊", "👨‍👩‍👧‍👦", "1.5", "但", "\ufeff"]
        for _ in range(200):
            text = "".join(rng.choices(atoms, k=30))
            self.assertEqual(segment(text), segment(text))
